// Generate SQL insert statements
export function generateSql() {
  const statements = featuresToInsert.map((f) => {
    const val = f.value === null ? 'NULL' : f.value
    const txtVal = f.text_value ? `'${f.text_value}'` : 'NULL'
    const notes = `'${f.quality_notes.replace(/'/g, "''")}'`
    const period = `'${f.measurement_period.replace(/'/g, "''")}'`
    const res = `'${f.spatial_resolution.replace(/'/g, "''")}'`
    const unit = f.unit ? `'${f.unit}'` : "''"

    return `INSERT INTO environmental_features (id, location_id, source_id, feature_name, value, text_value, unit, measurement_period, spatial_resolution, quality_notes)
VALUES ('${f.id}', '${f.location_id}', '${f.source_id}', '${f.feature_name}', ${val}, ${txtVal}, ${unit}, ${period}, ${res}, ${notes})
ON CONFLICT (id) DO UPDATE SET
  value = EXCLUDED.value,
  text_value = EXCLUDED.text_value,
  unit = EXCLUDED.unit,
  measurement_period = EXCLUDED.measurement_period,
  spatial_resolution = EXCLUDED.spatial_resolution,
  quality_notes = EXCLUDED.quality_notes;`
  })

  return statements.join('\n')
}

if (process.argv[1]?.endsWith('seed-scientific-features.mjs')) {
  fs.writeFileSync('scripts/seed-scientific-features.sql', generateSql(), 'utf8')
  console.log(`Generated SQL for ${featuresToInsert.length} scientific features.`)
}
